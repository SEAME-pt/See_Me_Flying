#!/usr/bin/env bash
# Creates .env for the SEA:ME dev container from your host's user/group IDs.
# Usage: ./make-env.sh [ROS_DOMAIN_ID]     e.g. ./make-env.sh 42
set -euo pipefail

# Always write .env next to compose.yaml, wherever the script is called from.
cd "$(dirname "$0")"

if [[ $EUID -eq 0 ]]; then
  echo "Don't run this with sudo: it would record root's IDs (0) instead of yours." >&2
  exit 1
fi

domain="${1:-}"
if [[ -z "$domain" ]]; then
  read -rp "Team ROS_DOMAIN_ID (0-101) [42]: " domain
  domain="${domain:-42}"
fi
if ! [[ "$domain" =~ ^[0-9]+$ ]] || (( domain > 101 )); then
  echo "ROS_DOMAIN_ID must be a number from 0 to 101 (got '$domain')." >&2
  exit 1
fi

if [[ -f .env ]]; then
  read -rp ".env already exists. Overwrite? [y/N]: " ans
  [[ "$ans" =~ ^[Yy]$ ]] || { echo "Left .env unchanged."; exit 0; }
fi

cat > .env << ENV
# Generated by make-env.sh on $(date -I). Do NOT commit.
HOST_UID=$(id -u)
HOST_GID=$(id -g)
ROS_DOMAIN_ID=$domain
ENV

echo "Wrote .env:"
grep -v '^#' .env
echo
echo "Next: docker compose build && docker compose up -d"
